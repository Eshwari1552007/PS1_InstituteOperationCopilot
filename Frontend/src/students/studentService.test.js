import { vi } from 'vitest';
import { normalizeStudent } from './studentService';

vi.mock('../firebase', () => ({ db: {} }));

const validStudent = {
  studentId: '', fullName: '  Mira   Shah ', email: ' MIRA@EXAMPLE.COM ', phone: ' 1234567890 ',
  course: ' Science ', batch: ' 2026-A ', admissionDate: '2026-06-01', status: 'active',
};

test('leaves new Student ID generation to the transactional enrollment service', () => {
  expect(normalizeStudent(validStudent)).toMatchObject({
    studentId: '', fullName: 'Mira Shah', email: 'mira@example.com', phone: '1234567890',
    course: 'Science', batch: '2026-A', status: 'ACTIVE',
  });
});

test('rejects invalid required fields with field-level errors', () => {
  expect.assertions(3);
  try {
    normalizeStudent({ ...validStudent, studentId: 'bad/id', email: 'invalid' });
  } catch (error) {
    expect(error.code).toBe('validation/invalid-data');
    expect(error.fields.studentId).toMatch(/generated by EDUPILOT/i);
    expect(error.fields.email).toMatch(/valid email/i);
  }
});
