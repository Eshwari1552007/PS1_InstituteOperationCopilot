import {
  collection,
  doc,
  getDocs,
  query,
  runTransaction,
  serverTimestamp,
  where,
} from 'firebase/firestore';
import { db } from '../firebase';
import { createStudentAndEnroll, transferStudent, updateStudentDetails } from '../batches/academyService';

const STUDENT_COLLECTION = 'students';
const ALLOWED_STATUSES = ['ACTIVE', 'PENDING', 'INACTIVE'];

export function normalizeStudent(input) {
  const student = {
    studentId: String(input.studentId || '').trim().toUpperCase(),
    ...(input.authUid ? { authUid: String(input.authUid).trim() } : {}),
    fullName: String(input.fullName || '').trim().replace(/\s+/g, ' '),
    email: String(input.email || '').trim().toLowerCase(),
    phone: String(input.phone || '').trim(),
    dateOfBirth: String(input.dateOfBirth || '').trim(),
    gender: String(input.gender || '').trim(),
    course: String(input.course || '').trim(),
    batch: String(input.batch || '').trim(),
    admissionDate: String(input.admissionDate || '').trim(),
    status: String(input.status || 'ACTIVE').trim().toUpperCase(),
    address: String(input.address || '').trim(),
    guardianName: String(input.guardianName || '').trim(),
    guardianPhone: String(input.guardianPhone || '').trim(),
    ...(input.initialPaymentAmount !== undefined ? { initialPaymentAmount: input.initialPaymentAmount } : {}),
    ...(input.learningMode ? { learningMode: input.learningMode } : {}),
  };
  const errors = {};
  if (student.studentId && !/^STU-\d{4}-\d{4,}$/.test(student.studentId)) errors.studentId = 'Student IDs are generated by EDUPILOT and cannot be changed.';
  if (student.fullName.length < 2) errors.fullName = 'Enter the student’s full name.';
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(student.email)) errors.email = 'Enter a valid email address.';
  if (!student.phone) errors.phone = 'Enter a phone number.';
  if (!/^\d{4}-\d{2}-\d{2}$/.test(student.admissionDate)) errors.admissionDate = 'Choose an admission date.';
  if (!ALLOWED_STATUSES.includes(student.status)) errors.status = 'Choose a valid student status.';
  if (Object.keys(errors).length) {
    const error = new Error('Please correct the highlighted fields.');
    error.code = 'validation/invalid-data';
    error.fields = errors;
    throw error;
  }
  return student;
}

function explainFirestoreError(error) {
  if (error.code === 'permission-denied') return new Error('You do not have permission to manage student records.');
  if (error.code === 'unavailable' || error.code === 'deadline-exceeded') return new Error('Firebase is temporarily unavailable. Check your connection and retry.');
  return error;
}

export async function listStudents(role) {
  const sources = [getDocs(collection(db, STUDENT_COLLECTION))];
  if (role === 'OWNER') {
    sources.push(getDocs(query(collection(db, 'users'), where('role', '==', 'STUDENT'))));
  }
  const [directoryResult, profilesResult] = await Promise.allSettled(sources);
  const directoryAvailable = directoryResult.status === 'fulfilled';
  const profilesAvailable = profilesResult?.status === 'fulfilled';
  if (!directoryAvailable && !profilesAvailable) {
    throw explainFirestoreError(directoryResult.reason);
  }

  const records = directoryAvailable
    ? directoryResult.value.docs.map((item) => ({ documentId: item.id, source: 'student-record', ...item.data() })).filter((item) => !item.isArchived)
    : [];
  if (directoryAvailable) {
    try {
      const enrollmentSnapshot = await getDocs(collection(db, 'enrollments'));
      const enrollmentByStudent = new Map();
      enrollmentSnapshot.docs.forEach((item) => {
        const record = item.data();
        if (record.status !== 'ACTIVE') return;
        const current = enrollmentByStudent.get(record.studentDocId) || [];
        current.push({ enrollmentId: item.id, courseName: record.courseName, batchName: record.batchName || record.batchId, batchId: record.batchId, learningMode: record.learningMode || 'OFFLINE', feeRecordId: record.feeRecordId });
        enrollmentByStudent.set(record.studentDocId, current);
      });
      records.forEach((student) => { student.enrollments = enrollmentByStudent.get(student.documentId) || []; });
    } catch { records.forEach((student) => { student.enrollments = []; }); }
    // Counselors manage admissions and rosters but cannot read the financial
    // collections or see payment summaries in the student directory.
    if (role !== 'COUNSELOR' && directoryAvailable) {
      try {
        const feeSnapshot = await getDocs(collection(db, 'feeRecords'));
        const feeByStudent = new Map();
        feeSnapshot.docs.forEach((item) => {
          const fee = item.data(); const current = feeByStudent.get(fee.studentDocId) || { totalFees: 0, amountPaid: 0, remainingBalance: 0 };
          current.totalFees += Number(fee.totalFee || 0); current.amountPaid += Number(fee.amountPaid || 0); current.remainingBalance += Number(fee.remainingBalance || 0);
          feeByStudent.set(fee.studentDocId, current);
        });
        records.forEach((student) => { const amounts = feeByStudent.get(student.documentId) || { totalFees: 0, amountPaid: 0, remainingBalance: 0 }; Object.assign(student, amounts, { paymentStatus: amounts.remainingBalance <= 0 && amounts.totalFees > 0 ? 'PAID' : amounts.amountPaid > 0 ? 'PARTIALLY_PAID' : 'UNPAID' }); });
      } catch { /* keep academic records available if finance reads are unavailable */ }
    }
  }
  const knownEmails = new Set(records.map((item) => String(item.email || '').trim().toLowerCase()).filter(Boolean));
  if (profilesAvailable) {
    profilesResult.value.docs.forEach((item) => {
      const profile = item.data();
      const email = String(profile.email || '').trim().toLowerCase();
      if (email && knownEmails.has(email)) return;
      if (email) knownEmails.add(email);
      records.push({
        documentId: item.id,
        source: 'account-profile',
        accountStatus: profile.status || 'UNKNOWN',
        studentId: '',
        fullName: profile.name || '',
        email,
        phone: '',
        dateOfBirth: '',
        gender: '',
        course: '',
        batch: '',
        admissionDate: '',
        status: profile.status === 'APPROVED' ? 'ACTIVE' : profile.status === 'PENDING' ? 'PENDING' : 'INACTIVE',
        address: '',
        guardianName: '',
        guardianPhone: '',
        createdAt: profile.createdAt,
      });
    });
  }

  const warnings = [];
  if (!directoryAvailable) {
    warnings.push(directoryResult.reason.code === 'permission-denied'
      ? 'Firestore denied access to the students collection. Showing Student account profiles only; deploy the updated Firestore rules to load full student records.'
      : `Could not load full student records: ${directoryResult.reason.message}`);
  }
  if (sources.length > 1 && !profilesAvailable) {
    warnings.push('Existing Student account profiles could not be loaded. Check that the signed-in account is an approved Owner.');
  }
  return { records, warnings };
}

export async function saveStudent(input, actorUid, existingDocumentId = '') {
  const student = normalizeStudent(input);
  if (!existingDocumentId && (!input.courseDocId || !input.batchDocId)) {
    const error = new Error('Select an active course and an available batch to register the student.');
    error.code = 'validation/invalid-data';
    error.fields = { courseDocId: !input.courseDocId ? 'Select a course.' : '', batchDocId: !input.batchDocId ? 'Select an available batch.' : '' };
    throw error;
  }
  if (existingDocumentId && Boolean(input.courseDocId) !== Boolean(input.batchDocId)) {
    const error = new Error('Choose both a course and batch to change the student’s enrollment.');
    error.code = 'validation/invalid-data';
    error.fields = { courseDocId: !input.courseDocId ? 'Select a course.' : '', batchDocId: !input.batchDocId ? 'Select a batch.' : '' };
    throw error;
  }
  if (existingDocumentId && input.courseDocId && input.batchDocId) {
    return transferStudent(existingDocumentId, input.courseDocId, input.batchDocId, actorUid, student);
  }
  if (existingDocumentId) return updateStudentDetails(existingDocumentId, student, actorUid);
  return createStudentAndEnroll(student, actorUid, input.courseDocId, input.batchDocId);
}

export async function removeStudent(documentId, actorUid) {
  try {
    await runTransaction(db, async (transaction) => {
      const ref = doc(db, STUDENT_COLLECTION, documentId);
      const snapshot = await transaction.get(ref);
      if (!snapshot.exists()) throw new Error('Student record not found.');
      if (snapshot.data().enrollmentStatus === 'ACTIVE') throw new Error('Transfer or withdraw this student before archiving the record.');
      transaction.update(ref, { isArchived: true, updatedAt: serverTimestamp(), updatedBy: actorUid });
    });
  } catch (error) {
    throw explainFirestoreError(error);
  }
}
